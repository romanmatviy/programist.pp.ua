export function getTechSEOData(slug: string, category: string, lang: 'ua' | 'ru', techName: string): TechDetail {
  const normalizedSlug = slug.toLowerCase();
  
  if (specificTechTexts[normalizedSlug]) {
    return specificTechTexts[normalizedSlug][lang];
  }
  
  const categoryKey = category && defaultTexts[category] ? category : 'Backend';
  const data = defaultTexts[categoryKey][lang];
  
  return {
    ...data,
    intro: data.intro.replace(/технологія|технология/g, techName),
  };
}
